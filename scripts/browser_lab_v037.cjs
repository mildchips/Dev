const {chromium}=require(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES+'/playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.route('**/*',route=>route.request().url().startsWith('http://127.0.0.1:8766/')?route.continue():route.abort());
 await page.goto('http://127.0.0.1:8766/');
 await page.fill('#login-name','synthetic-browser-owner');await page.fill('#password','Synthetic-browser-password-037');
 await page.click('#login button');await page.waitForSelector('#workspace:not([hidden])');
 await page.fill('#store-label','<img src=x onerror=alert(1)>');await page.click('#store button');
 await page.waitForFunction(()=>document.querySelector('#stores').textContent.includes('<img src=x onerror=alert(1)>'));
 if(await page.locator('#stores img').count())throw Error('unescaped store label');
 await page.fill('#invite-login','synthetic-browser-manager');await page.click('#invite button');
 await page.waitForFunction(()=>document.querySelector('#new-invite').textContent.includes('Одноразовый код:'));
 const token=(await page.textContent('#new-invite')).split(': ')[1];
 await page.click('#logout');await page.waitForSelector('#login:not([hidden])');
 await page.fill('#login-name','synthetic-browser-manager');await page.fill('#password','Synthetic-browser-password-037');await page.click('#login button');
 await page.waitForSelector('#workspace:not([hidden])');await page.fill('#invite-token',token);await page.click('#accept button');
 await page.waitForFunction(()=>document.querySelector('#stores').textContent.includes('SYNTHETIC BROWSER STORE'));
 if(await page.locator('#owner-tools').isVisible())throw Error('owner controls visible to manager');
 await page.getByRole('button',{name:'Создать тестовую задачу'}).click();
 await page.waitForFunction(()=>document.querySelector('#results').textContent.includes('Выполните python'));
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw Error('mobile overflow');
 if(errors.length)throw Error(errors.join('\n'));
 fs.writeFileSync(process.argv[2],JSON.stringify({status:'PASS',desktop:'1280x900',mobile:'390x844',checks:['owner login','store creation','XSS escaping','invitation','logout','manager login','acceptance','owner controls hidden','synthetic enqueue','mobile no overflow'],page_errors:errors},null,2));
 await browser.close();
})().catch(error=>{console.error(error.message);process.exit(1)});
